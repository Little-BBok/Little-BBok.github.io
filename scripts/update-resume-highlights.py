"""Regenerate highlight rectangles from the current English resume (requires pdftotext)."""
import json
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = [
    ("reviews", "소비자 리뷰 1,061건 분석 및 국내 메시지 제안", "Consumer review analysis and Korean-market messaging", ["1,061 Japanese-language reviews"]),
    ("partnerships", "POWAPOWA 론칭 및 큐텐 재팬·메리어트 목시 협업 제안 유치", "POWAPOWA launch and inbound proposals from Qoo10 Japan and Marriott’s Moxy", ["Launched POWAPOWA,", "collaboration proposals from Qoo10 Japan and Marriott's Moxy Seoul Insadong"]),
    ("product", "디바이스·패키지·이커머스 UX 기획 리드 및 생산 비용 24% 절감", "Device, packaging and e-commerce UX leadership; 24% lower production costs", ["Led device and packaging planning and e-commerce UX", "24%"]),
    ("growth", "인스타그램 팔로워 10명 → 1,707명 성장 및 UGC 48건 제작", "Instagram growth from 10 to 1,707 followers and 48 UGC assets", ["10 to 1,707 followers", "48 UGC assets"]),
    ("program", "아동 테스트를 거쳐 회사 공식 프로그램으로 채택된 커리큘럼 설계", "Curriculum adopted as an official company program after user testing", ["adoption as an official company program"]),
    ("began", "began 제품 기획 리드, UXIM × YCC 1위 및 썸머 워크스테이션 우수상", "Began product planning; UXIM × YCC 1st place and Summer Workstation Excellence Award", ["Led began's planning", "won 1st place at UXIM x YCC and an Excellence Award", "Summer Workstation showcase"]),
    ("marketing", "began 마케팅·외부 제휴 리드, 10일간 조회수 19,220회·신규 팔로워 365명", "Began marketing and partnerships; 19,220 views and 365 new followers in 10 days", ["service marketing and external partnership outreach;", "19,220 Instagram views and 365 new", "followers within the channel's first 10 days"]),
    ("travel", "여행 상품 누적 매출 17,000달러 달성", "USD 17,000 in cumulative travel-product sales", ["USD 17,000"]),
    ("kcc", "위치 기반 카메라 앱 기획·UI/UX 설계, 최종 피칭 1위 및 파트너사 상용 출시 기여", "Location-based camera app planning and UI/UX; 1st place and commercial launch", ["won 1st place in the final pitch,", "contributing to the partner company's commercial launch"]),
]
with tempfile.TemporaryDirectory() as directory:
    path = Path(directory) / "resume.html"
    subprocess.run(["pdftotext", "-bbox-layout", str(ROOT / "public/documents/resume/sumin-lee-resume.pdf"), str(path)], check=True)
    ns = {"h": "http://www.w3.org/1999/xhtml"}
    page = ET.parse(path).find(".//h:page", ns)
    width, height = float(page.attrib["width"]), float(page.attrib["height"])
    words = [(w, n) for n, line in enumerate(page.findall(".//h:line", ns)) for w in line]
    texts = [w.text or "" for w, _ in words]
    result = []
    for key, ko, en, phrases in TARGETS:
        rects = []
        for phrase in phrases:
            tokens = phrase.split()
            matches = [i for i in range(len(words)-len(tokens)+1) if texts[i:i+len(tokens)] == tokens]
            if len(matches) != 1:
                raise ValueError(f"Expected one match for {phrase!r}, got {len(matches)}. Review the updated PDF.")
            selected = words[matches[0]:matches[0]+len(tokens)]
            for line in dict.fromkeys(n for _, n in selected):
                group = [w for w, n in selected if n == line]
                left = min(float(w.attrib["xMin"]) for w in group)
                right = max(float(w.attrib["xMax"]) for w in group)
                top = min(float(w.attrib["yMin"]) for w in group)
                bottom = max(float(w.attrib["yMax"]) for w in group)
                rects.append({k: round(v, 5) for k,v in dict(left=left/width*100, top=top/height*100, width=(right-left)/width*100, height=(bottom-top)/height*100).items()})
        result.append(dict(id=key, ko=ko, en=en, rects=rects))
    (ROOT / "src/data/resumeHighlights.ts").write_text("// Generated by scripts/update-resume-highlights.py from the current PDF.\nexport const resumeHighlights = " + json.dumps(result, ensure_ascii=False, indent=2) + ";\n")
